// Writes docs/CHECKS.md from the check engine's own catalog (listChecks + explainCheck), so
// the doc never drifts from the shipped checks.
//
//   node scripts/gen-checks-doc.mjs           write docs/CHECKS.md
//   node scripts/gen-checks-doc.mjs --check   exit 1 when docs/CHECKS.md is out of date
//
// Build first (pnpm build).

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "docs", "CHECKS.md");
const check = process.argv.includes("--check");

const { listChecks, explainCheck } = await import(
  pathToFileURL(path.join(root, "packages", "checks", "dist", "index.js")).href
);

const GROUP_NAMES = {
  measurement: "Measurement and conversion tracking",
  structure: "Account structure",
  budget_bidding: "Budgets and bidding",
  search: "Search campaigns",
  pmax: "Performance Max",
  slices: "Devices, locations, times",
  trends: "Trends over time",
  presence: "Presence",
  cross_tree: "Across campaign types",
};

const cell = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\s*\n\s*/g, " ");

const render = () => {
  const checks = listChecks();
  const groups = [...new Set(checks.map((c) => c.group))];
  const lines = [
    "# Account checks",
    "",
    "<!-- Generated by scripts/gen-checks-doc.mjs from the check engine's catalog. Do not edit by hand: run `node scripts/gen-checks-doc.mjs` after changing a check. -->",
    "",
    `${checks.length} deterministic checks: no AI, no network, same snapshot in = same result out. Run them with \`build_snapshot\` then \`run_checks\` (or the \`weekly_audit\` prompt). \`explain_check\` shows one check in full; the resource \`checks://catalog\` lists them.`,
    "",
    "Every check ends in one state: **finding** (it found something), **info** (a note, not a fault), **clean** (it judged real data and found nothing), **not_run** (it could not judge: a table was not read, was cut, or the check does not apply; never counted as clean) or **suppressed** (it found something, but a confounder or a paused entity explains it).",
    "",
    "Default settings: the threshold values each check uses (`explain_check` shows them too).",
    "",
    'Technical users can change a threshold for one run: pass `settings` to `run_checks`, for example `{"search": {"rsaMinHeadlines": 8}}`.',
    "",
    "| Group | Checks |",
    "| --- | --- |",
    ...groups.map(
      (g) =>
        `| [${GROUP_NAMES[g] ?? g}](#${(GROUP_NAMES[g] ?? g)
          .toLowerCase()
          .replace(/[^a-z0-9 -]/g, "")
          .replace(/ /g, "-")}) | ${checks.filter((c) => c.group === g).length} |`,
    ),
    "",
  ];
  for (const g of groups) {
    lines.push(
      `## ${GROUP_NAMES[g] ?? g}`,
      "",
      "| Id | Check | Can reach | Needs | Default settings |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const c of checks.filter((x) => x.group === g)) {
      const settings = Object.entries(explainCheck(c.id)?.settings ?? {})
        .map(([k, v]) => `\`${k}\` ${v}`)
        .join(", ");
      const reach = c.infoLine
        ? "info only"
        : c.emitsFindings
          ? c.maxSeverity
          : "context for other checks";
      lines.push(
        `| ${c.id} | ${cell(c.title)}${c.noneFoundMeans ? `<br>Clean means: ${cell(c.noneFoundMeans)}` : ""} | ${reach} | ${cell(c.dependsOn.join(", "))} | ${cell(settings || "-")} |`,
      );
    }
    lines.push("");
  }
  return lines.join("\n");
};

const text = render();
if (check) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing file = out of date
  }
  if (current !== text) {
    console.error(
      "docs/CHECKS.md is out of date with the check catalog. Run: node scripts/gen-checks-doc.mjs",
    );
    process.exit(1);
  }
  console.log("docs/CHECKS.md is up to date.");
} else {
  writeFileSync(target, text);
  console.log(`Wrote docs/CHECKS.md (${text.length} bytes).`);
}
