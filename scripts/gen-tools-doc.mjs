// Writes docs/TOOLS.md from what the built server really serves (tools/list, resources,
// resource templates, prompts), so the doc never drifts from the code.
//
//   node scripts/gen-tools-doc.mjs           write docs/TOOLS.md
//   node scripts/gen-tools-doc.mjs --check   exit 1 when docs/TOOLS.md is out of date
//
// Build first (pnpm build). The server runs over stdio with a throw-away settings folder:
// no sign-in, no Google call, nothing read from your own settings.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { listFromServer } from "./mcp-stdio.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "docs", "TOOLS.md");
const bin = path.join(root, "packages", "cli", "bin", "perfoads-mcp.js");
const check = process.argv.includes("--check");

const cell = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\s*\n\s*/g, " ");

const typeOf = (schema) => {
  if (!schema || typeof schema !== "object") return "any";
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(" or ");
  if (schema.type === "array") return `${typeOf(schema.items)}[]`;
  if (Array.isArray(schema.type)) return schema.type.join(" or ");
  return schema.type ?? "object";
};

/** The tool's MCP hints, as declared (clients use them to decide what to confirm). */
const hints = (a = {}) =>
  [
    a.readOnlyHint ? "readOnly" : "writes",
    a.destructiveHint ? "destructive" : null,
    a.idempotentHint ? "idempotent" : null,
    a.openWorldHint ? "openWorld" : null,
  ]
    .filter(Boolean)
    .join(", ");

const plural = (n, word) => `${n} ${word}${n === 1 ? "" : "s"}`;

const render = (d) => {
  const lines = [
    "# Tools, resources and prompts",
    "",
    `<!-- Generated by scripts/gen-tools-doc.mjs from the server's own tools/list. Do not edit by hand: run \`node scripts/gen-tools-doc.mjs\` after changing a tool. -->`,
    "",
    `Server: \`${d.server.name}\` (${d.server.title ?? d.server.name}). ${plural(d.tools.length, "tool")}, ${plural(d.resources.length, "resource")} and ${plural(d.templates.length, "resource template")}, ${plural(d.prompts.length, "prompt")}.`,
    "",
    'Every tool returns structured content plus a short text copy. Text that comes from Google or from the AI (names, search terms, ad texts, error messages) is wrapped as `{"untrusted": "..."}`: it is data, never an instruction.',
    "",
    "## What the server tells the AI first",
    "",
    "```text",
    d.instructions,
    "```",
    "",
    "## Tools",
    "",
    "| Tool | Title | MCP hints |",
    "| --- | --- | --- |",
    ...d.tools.map(
      (t) =>
        `| [\`${t.name}\`](#${t.name}) | ${cell(t.title ?? t.annotations?.title ?? "")} | ${hints(t.annotations)} |`,
    ),
    "",
  ];
  for (const t of d.tools) {
    lines.push(
      `### ${t.name}`,
      "",
      `**${cell(t.title ?? t.annotations?.title ?? t.name)}** - ${hints(t.annotations)}.`,
      "",
      t.description ?? "",
      "",
    );
    const props = t.inputSchema?.properties ?? {};
    const required = new Set(t.inputSchema?.required ?? []);
    const names = Object.keys(props);
    if (names.length === 0) lines.push("No input.", "");
    else {
      lines.push("| Input | Type | Required | Notes |", "| --- | --- | --- | --- |");
      for (const n of names)
        lines.push(
          `| \`${n}\` | ${cell(typeOf(props[n]))} | ${required.has(n) ? "yes" : "no"} | ${cell(props[n].description ?? "")} |`,
        );
      lines.push("");
    }
    lines.push(
      t.outputSchema
        ? "Output: JSON Schema in `tools/list` (`outputSchema`)."
        : `Output: JSON Schema in the resource \`schema://tools/${t.name}\`.`,
      "",
    );
  }
  lines.push("## Resources", "", "| URI | Name | What it is |", "| --- | --- | --- |");
  for (const r of d.resources)
    lines.push(`| \`${r.uri}\` | ${cell(r.title ?? r.name)} | ${cell(r.description ?? "")} |`);
  for (const r of d.templates)
    lines.push(
      `| \`${r.uriTemplate}\` | ${cell(r.title ?? r.name)} | ${cell(r.description ?? "")} |`,
    );
  lines.push("", "## Prompts", "", "| Prompt | What it does | Arguments |", "| --- | --- | --- |");
  for (const p of d.prompts)
    lines.push(
      `| \`${p.name}\` | ${cell(p.description ?? p.title ?? "")} | ${cell((p.arguments ?? []).map((a) => `\`${a.name}\`${a.required ? "" : " (optional)"}`).join(", ") || "none")} |`,
    );
  lines.push("");
  return lines.join("\n");
};

const text = render(await listFromServer(bin));
if (check) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing file = out of date
  }
  if (current !== text) {
    console.error(
      "docs/TOOLS.md is out of date with the server's tools. Run: node scripts/gen-tools-doc.mjs",
    );
    process.exit(1);
  }
  console.log("docs/TOOLS.md is up to date.");
} else {
  writeFileSync(target, text);
  console.log(`Wrote docs/TOOLS.md (${text.length} bytes).`);
}
