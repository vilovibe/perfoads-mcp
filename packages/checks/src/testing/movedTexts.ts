export const MIN_CHUNK = 20;

/**
 * Every string-literal piece of 20+ characters in a file: "...", '...' and the
 * fixed parts of `...${x}...`, trimmed. Each quote kind is scanned on its own
 * so a stray apostrophe in a comment cannot hide a string of another kind.
 */
export function literalChunks(text: string): Set<string> {
  const out = new Set<string>();
  for (const re of [/"((?:[^"\\\n]|\\.)*)"/g, /'((?:[^'\\\n]|\\.)*)'/g, /`((?:[^`\\]|\\.)*)`/g]) {
    for (const m of text.matchAll(re))
      for (const part of (m[1] ?? "").split(/\$\{[^}]*\}/)) {
        const t = part.trim();
        if (t.length >= MIN_CHUNK) out.add(t);
      }
  }
  return out;
}

/** sha256 as hex written with the letters g-v (no digits, nothing a secret scanner reads as a key). */
